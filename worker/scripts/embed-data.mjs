#!/usr/bin/env node
/**
 * Embed committed public baselines, briefs, and the privacy policy into
 * worker/src/embedded.ts so the Worker can run offline from the repo.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const workerRoot = path.resolve(here, "..");
const repoRoot = path.resolve(workerRoot, "..");
const baselinesDir = path.join(repoRoot, "data/baselines");
const briefsDir = path.join(repoRoot, "data/briefs");
const privacyPath = path.join(repoRoot, "docs/privacy.md");
const outPath = path.join(workerRoot, "src/embedded.ts");

function readJsonFiles(dir) {
  if (!fs.existsSync(dir)) {
    throw new Error(`Missing ${dir}`);
  }
  return fs
    .readdirSync(dir)
    .filter((name) => name.endsWith(".json"))
    .sort()
    .map((name) => {
      const raw = fs.readFileSync(path.join(dir, name), "utf8");
      return JSON.parse(raw);
    });
}

function readBriefs(dir) {
  const briefs = {};
  if (!fs.existsSync(dir)) {
    return briefs;
  }
  for (const name of fs.readdirSync(dir).sort()) {
    if (!name.endsWith(".md")) continue;
    const date = name.slice(0, -3);
    briefs[date] = fs.readFileSync(path.join(dir, name), "utf8");
  }
  return briefs;
}

const baselines = readJsonFiles(baselinesDir);
const briefs = readBriefs(briefsDir);
const privacy = fs.readFileSync(privacyPath, "utf8");

const header = `/* AUTO-GENERATED by worker/scripts/embed-data.mjs — do not edit.
 * Source: data/baselines, data/briefs, docs/privacy.md
 */
`;

const body = `${header}
export const RAW_BASELINES: unknown[] = ${JSON.stringify(baselines, null, 2)};

export const BRIEFS: Record<string, string> = ${JSON.stringify(briefs, null, 2)};

export const PRIVACY_MARKDOWN: string = ${JSON.stringify(privacy)};
`;

fs.writeFileSync(outPath, body);
console.log(
  `wrote ${path.relative(repoRoot, outPath)} (${baselines.length} baselines, ${Object.keys(briefs).length} briefs)`,
);
